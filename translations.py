"""
Phantom - translations.

To add a language: copy the English block, translate the text after " = ",
add the language code to LANGUAGES and to STRINGS at the bottom.
Placeholders like {name} must stay unchanged. "\n" means a line break.
"""


def _parse(text: str) -> dict:
    d = {}
    for line in text.strip().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        key, value = line.split(" = ", 1)
        d[key.strip()] = value.strip().replace("\\n", "\n")
    return d


